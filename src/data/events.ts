import { EventItem, Seat, SeatSection } from '../types';

function generateSeats(sectionName: string, rowLetters: string[], seatsPerRow: number, tierId: string, price: number, soldIndices: number[]): SeatSection {
  return {
    name: sectionName,
    rows: rowLetters.map((row) => {
      const seats: Seat[] = [];
      for (let i = 1; i <= seatsPerRow; i++) {
        const id = `${row}-${i}`;
        const isSold = soldIndices.includes(i) || (row === 'B' && (i === 3 || i === 4)) || (row === 'D' && i === 7);
        seats.push({
          id,
          row,
          number: i,
          tierId,
          price,
          status: isSold ? 'sold' : 'available',
        });
      }
      return { row, seats };
    }),
  };
}

